// Optimizes selected GLBs from the Unity project into public/media/models and
// regenerates src/data/credits.ts from each source file's asset.extras (Sketchfab metadata).
// Usage: npm run media:models [-- --game ../3DTester]
import { execSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { gameDir, kb, root } from './lib/media.mjs'

const srcDir = join(gameDir(), 'Assets/Art/Props/OldHouse')
const outDir = join(root, 'public/media/models')

const MODELS = [
  // altar set
  'AnhTho',
  'DenTho',
  'luhuong',
  'HoaCuc',
  'tutho',
  // grocery shelf
  'NuocMam',
  'TuongOt',
  'Muoi',
  'BanhMi',
  'chennuoc',
]

const MAX_BYTES = 1.5 * 1024 * 1024
const TOTAL_BUDGET = 8 * 1024 * 1024

// Each pass is tried in order until the output fits MAX_BYTES.
const PASSES = [
  ['--texture-size', '1024'],
  ['--texture-size', '1024', '--simplify-error', '0.001'],
  ['--texture-size', '1024', '--simplify-error', '0.004'],
  ['--texture-size', '512', '--simplify-error', '0.004'],
  ['--texture-size', '512', '--simplify-error', '0.01'],
]

function readGlbJson(file) {
  const buf = readFileSync(file)
  if (buf.readUInt32LE(0) !== 0x46546c67) throw new Error(`${file} is not a GLB`)
  const length = buf.readUInt32LE(12)
  return JSON.parse(buf.subarray(20, 20 + length).toString('utf8'))
}

function optimize(input, output, pass) {
  // One command string: npx is a .cmd shim on Windows, which only runs through a shell.
  const cmd = [
    'npx --yes @gltf-transform/cli@4 optimize',
    `"${input}"`,
    `"${output}"`,
    '--compress meshopt --texture-compress webp',
    ...pass,
  ].join(' ')
  execSync(cmd, { stdio: ['ignore', 'ignore', 'inherit'] })
  return statSync(output).size
}

mkdirSync(outDir, { recursive: true })
const credits = []
let total = 0

for (const name of MODELS) {
  const input = join(srcDir, `${name}.glb`)
  if (!existsSync(input)) {
    console.warn(`! missing ${input}`)
    continue
  }
  const output = join(outDir, `${name}.glb`)
  let size = 0
  let used = PASSES[0]
  for (const pass of PASSES) {
    used = pass
    size = optimize(input, output, pass)
    if (size <= MAX_BYTES) break
  }
  total += size
  const flag = size > MAX_BYTES ? '  (over 1.5 MB budget)' : ''
  console.log(
    `${name.padEnd(10)} ${kb(statSync(input).size).padStart(9)} -> ${kb(size).padStart(7)}  [${used.join(' ')}]${flag}`,
  )

  const extras = readGlbJson(input).asset?.extras
  if (extras?.author || extras?.license) {
    const parse = (s = '') => {
      const m = /^(.*?)\s*\((https?:\/\/[^)]+)\)\s*$/.exec(s)
      return m ? { text: m[1], url: m[2] } : { text: s, url: undefined }
    }
    const author = parse(extras.author)
    const license = parse(extras.license)
    credits.push({
      model: name,
      title: extras.title ?? name,
      author: author.text,
      authorUrl: author.url,
      license: license.text,
      licenseUrl: license.url,
      source: extras.source,
    })
  }
}

console.log(`total      ${kb(total)}${total > TOTAL_BUDGET ? '  (over 8 MB budget)' : ''}`)

const ts = `// Generated by scripts/optimize-models.mjs from each GLB's asset.extras. Do not edit by hand;
// re-run \`npm run media:models\`. Every model listed here must be credited visibly on the site.
export interface ModelCredit {
  /** File name in public/media/models, without extension */
  model: string
  title: string
  author: string
  authorUrl?: string
  license: string
  licenseUrl?: string
  source?: string
}

export const modelCredits: ModelCredit[] = ${JSON.stringify(credits, null, 2)}
`
const creditsFile = join(root, 'src/data/credits.ts')
mkdirSync(dirname(creditsFile), { recursive: true })
writeFileSync(creditsFile, ts)
execSync(`npx prettier --write "${creditsFile}"`, { stdio: 'ignore' })
console.log(`wrote ${credits.length} credit(s) to src/data/credits.ts`)
